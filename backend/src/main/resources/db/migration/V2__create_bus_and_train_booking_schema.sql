-- PostgreSQL 17. Business data is intentionally not seeded.
-- Composite foreign keys keep copied type/trip/order identifiers consistent.
-- Stop orders are positive, contiguous integers assigned before a trip opens.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL CHECK (btrim(full_name) <> ''),
    email VARCHAR(254) NOT NULL UNIQUE CHECK (email = lower(btrim(email)) AND email <> ''),
    password_hash VARCHAR(255) NOT NULL,
    phone VARCHAR(25),
    role VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER' CHECK (role IN ('CUSTOMER', 'ADMIN')),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'LOCKED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE stations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    station_type VARCHAR(10) NOT NULL CHECK (station_type IN ('BUS', 'TRAIN')),
    province_city VARCHAR(100) NOT NULL,
    address VARCHAR(300) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id, station_type)
);

CREATE TABLE routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    transport_type VARCHAR(10) NOT NULL CHECK (transport_type IN ('BUS', 'TRAIN')),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id, transport_type)
);

CREATE TABLE route_stops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL,
    station_id BIGINT NOT NULL,
    transport_type VARCHAR(10) NOT NULL,
    stop_order INTEGER NOT NULL CHECK (stop_order > 0),
    distance_from_origin_km NUMERIC(10,2) NOT NULL CHECK (distance_from_origin_km >= 0),
    FOREIGN KEY (route_id, transport_type) REFERENCES routes (id, transport_type),
    FOREIGN KEY (station_id, transport_type) REFERENCES stations (id, station_type),
    UNIQUE (route_id, stop_order)
);

CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    transport_type VARCHAR(10) NOT NULL CHECK (transport_type IN ('BUS', 'TRAIN')),
    license_plate VARCHAR(20) UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'MAINTENANCE', 'INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((transport_type = 'BUS' AND license_plate IS NOT NULL AND btrim(license_plate) <> '')
        OR (transport_type = 'TRAIN' AND license_plate IS NULL)),
    UNIQUE (id, transport_type)
);

CREATE TABLE vehicle_carriages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL,
    transport_type VARCHAR(10) NOT NULL DEFAULT 'TRAIN' CHECK (transport_type = 'TRAIN'),
    carriage_number VARCHAR(20) NOT NULL,
    carriage_type VARCHAR(20) NOT NULL CHECK (carriage_type IN ('SEATED', 'SLEEPER', 'MIXED')),
    display_order INTEGER NOT NULL CHECK (display_order > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (vehicle_id, transport_type) REFERENCES vehicles (id, transport_type),
    UNIQUE (vehicle_id, carriage_number),
    UNIQUE (vehicle_id, display_order),
    UNIQUE (id, vehicle_id)
);

CREATE TABLE vehicle_seats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL,
    transport_type VARCHAR(10) NOT NULL,
    carriage_id BIGINT,
    seat_number VARCHAR(20) NOT NULL,
    seat_class VARCHAR(30) NOT NULL CHECK (seat_class IN ('STANDARD', 'SOFT_SEAT', 'SLEEPER', 'VIP')),
    floor_number SMALLINT NOT NULL DEFAULT 1 CHECK (floor_number > 0),
    row_number SMALLINT NOT NULL CHECK (row_number > 0),
    column_number SMALLINT NOT NULL CHECK (column_number > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (vehicle_id, transport_type) REFERENCES vehicles (id, transport_type),
    FOREIGN KEY (carriage_id, vehicle_id) REFERENCES vehicle_carriages (id, vehicle_id),
    CHECK ((transport_type = 'BUS' AND carriage_id IS NULL)
        OR (transport_type = 'TRAIN' AND carriage_id IS NOT NULL)),
    UNIQUE NULLS NOT DISTINCT (vehicle_id, carriage_id, seat_number),
    UNIQUE NULLS NOT DISTINCT (vehicle_id, carriage_id, floor_number, row_number, column_number),
    UNIQUE (id, vehicle_id)
);

CREATE TABLE trips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    route_id BIGINT NOT NULL,
    vehicle_id BIGINT NOT NULL,
    transport_type VARCHAR(10) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'SCHEDULED', 'DEPARTED', 'COMPLETED', 'CANCELLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (route_id, transport_type) REFERENCES routes (id, transport_type),
    FOREIGN KEY (vehicle_id, transport_type) REFERENCES vehicles (id, transport_type),
    UNIQUE (id, vehicle_id),
    UNIQUE (id, transport_type)
);

CREATE TABLE trip_stops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL,
    station_id BIGINT NOT NULL,
    transport_type VARCHAR(10) NOT NULL,
    stop_order INTEGER NOT NULL CHECK (stop_order > 0),
    arrival_time TIMESTAMPTZ,
    departure_time TIMESTAMPTZ,
    boarding_allowed BOOLEAN NOT NULL DEFAULT TRUE,
    alighting_allowed BOOLEAN NOT NULL DEFAULT TRUE,
    FOREIGN KEY (trip_id, transport_type) REFERENCES trips (id, transport_type),
    FOREIGN KEY (station_id, transport_type) REFERENCES stations (id, station_type),
    CHECK (arrival_time IS NOT NULL OR departure_time IS NOT NULL),
    CHECK (arrival_time IS NULL OR departure_time IS NULL OR arrival_time <= departure_time),
    CHECK (NOT boarding_allowed OR departure_time IS NOT NULL),
    CHECK (NOT alighting_allowed OR arrival_time IS NOT NULL),
    UNIQUE (trip_id, stop_order),
    UNIQUE (id, trip_id, stop_order)
);

CREATE TABLE trip_fares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL,
    origin_trip_stop_id BIGINT NOT NULL,
    destination_trip_stop_id BIGINT NOT NULL,
    origin_stop_order INTEGER NOT NULL,
    destination_stop_order INTEGER NOT NULL,
    seat_class VARCHAR(30) NOT NULL CHECK (seat_class IN ('STANDARD', 'SOFT_SEAT', 'SLEEPER', 'VIP')),
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'VND' CHECK (currency = 'VND'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (origin_trip_stop_id, trip_id, origin_stop_order) REFERENCES trip_stops (id, trip_id, stop_order),
    FOREIGN KEY (destination_trip_stop_id, trip_id, destination_stop_order) REFERENCES trip_stops (id, trip_id, stop_order),
    CHECK (origin_stop_order < destination_stop_order),
    UNIQUE (trip_id, origin_trip_stop_id, destination_trip_stop_id, seat_class)
);

CREATE TABLE trip_seats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL,
    vehicle_id BIGINT NOT NULL,
    vehicle_seat_id BIGINT NOT NULL,
    seat_number_snapshot VARCHAR(20) NOT NULL,
    carriage_number_snapshot VARCHAR(20),
    seat_class VARCHAR(30) NOT NULL CHECK (seat_class IN ('STANDARD', 'SOFT_SEAT', 'SLEEPER', 'VIP')),
    is_blocked BOOLEAN NOT NULL DEFAULT FALSE,
    FOREIGN KEY (trip_id, vehicle_id) REFERENCES trips (id, vehicle_id),
    FOREIGN KEY (vehicle_seat_id, vehicle_id) REFERENCES vehicle_seats (id, vehicle_id),
    UNIQUE (trip_id, vehicle_seat_id),
    UNIQUE (id, trip_id)
);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code VARCHAR(40) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES users (id),
    trip_id BIGINT NOT NULL,
    origin_trip_stop_id BIGINT NOT NULL,
    destination_trip_stop_id BIGINT NOT NULL,
    origin_stop_order INTEGER NOT NULL,
    destination_stop_order INTEGER NOT NULL,
    -- Contact/passenger details can be completed after the initial seat hold.
    contact_name VARCHAR(150),
    contact_phone VARCHAR(25),
    contact_email VARCHAR(254),
    total_amount NUMERIC(14,2) NOT NULL CHECK (total_amount > 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'VND' CHECK (currency = 'VND'),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING_PAYMENT'
        CHECK (status IN ('PENDING_PAYMENT', 'CONFIRMED', 'EXPIRED', 'CANCELLED')),
    expires_at TIMESTAMPTZ NOT NULL,
    confirmed_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    cancellation_reason VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (origin_trip_stop_id, trip_id, origin_stop_order) REFERENCES trip_stops (id, trip_id, stop_order),
    FOREIGN KEY (destination_trip_stop_id, trip_id, destination_stop_order) REFERENCES trip_stops (id, trip_id, stop_order),
    CHECK (origin_stop_order < destination_stop_order),
    CHECK (expires_at > created_at),
    CHECK (status <> 'CONFIRMED' OR (confirmed_at IS NOT NULL AND contact_name IS NOT NULL AND contact_phone IS NOT NULL)),
    CHECK (status <> 'CANCELLED' OR cancelled_at IS NOT NULL),
    UNIQUE (id, trip_id, origin_stop_order, destination_stop_order)
);

CREATE TABLE booking_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    trip_id BIGINT NOT NULL,
    trip_seat_id BIGINT NOT NULL,
    origin_stop_order INTEGER NOT NULL,
    destination_stop_order INTEGER NOT NULL,
    passenger_name VARCHAR(150),
    passenger_phone VARCHAR(25),
    unit_price NUMERIC(14,2) NOT NULL CHECK (unit_price > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (booking_id, trip_id, origin_stop_order, destination_stop_order)
        REFERENCES bookings (id, trip_id, origin_stop_order, destination_stop_order),
    FOREIGN KEY (trip_seat_id, trip_id) REFERENCES trip_seats (id, trip_id),
    UNIQUE (booking_id, trip_seat_id),
    UNIQUE (id, trip_id, trip_seat_id, origin_stop_order, destination_stop_order)
);

CREATE TABLE seat_segment_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL,
    trip_seat_id BIGINT NOT NULL,
    segment_start_trip_stop_id BIGINT NOT NULL,
    segment_end_trip_stop_id BIGINT NOT NULL,
    segment_start_order INTEGER NOT NULL,
    segment_end_order INTEGER NOT NULL,
    booking_item_id BIGINT NOT NULL,
    origin_stop_order INTEGER NOT NULL,
    destination_stop_order INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'HELD' CHECK (status IN ('HELD', 'BOOKED', 'RELEASED', 'EXPIRED')),
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (booking_item_id, trip_id, trip_seat_id, origin_stop_order, destination_stop_order)
        REFERENCES booking_items (id, trip_id, trip_seat_id, origin_stop_order, destination_stop_order),
    FOREIGN KEY (segment_start_trip_stop_id, trip_id, segment_start_order) REFERENCES trip_stops (id, trip_id, stop_order),
    FOREIGN KEY (segment_end_trip_stop_id, trip_id, segment_end_order) REFERENCES trip_stops (id, trip_id, stop_order),
    CHECK (segment_end_order = segment_start_order + 1),
    CHECK (segment_start_order >= origin_stop_order AND segment_end_order <= destination_stop_order),
    CHECK (expires_at > created_at)
);

-- Expiry alone does not remove a hold: explicitly transition HELD to EXPIRED
-- in the same transaction before reallocating. Never put now() in this index.
CREATE UNIQUE INDEX uq_active_seat_segment ON seat_segment_allocations (trip_seat_id, segment_start_trip_stop_id)
    WHERE status IN ('HELD', 'BOOKED');
CREATE INDEX idx_allocation_expiry ON seat_segment_allocations (expires_at) WHERE status = 'HELD';
CREATE INDEX idx_allocation_item ON seat_segment_allocations (booking_item_id);

CREATE TABLE payment_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings (id),
    provider VARCHAR(30) NOT NULL CHECK (btrim(provider) <> ''),
    payment_reference VARCHAR(100) NOT NULL UNIQUE,
    provider_transaction_id VARCHAR(150),
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'VND' CHECK (currency = 'VND'),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED', 'EXPIRED')),
    reconciliation_status VARCHAR(20) NOT NULL DEFAULT 'NONE' CHECK (reconciliation_status IN ('NONE', 'REVIEW_REQUIRED', 'RESOLVED')),
    paid_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ NOT NULL,
    failure_code VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (expires_at > created_at),
    CHECK (status <> 'SUCCEEDED' OR (paid_at IS NOT NULL AND provider_transaction_id IS NOT NULL)),
    UNIQUE (provider, provider_transaction_id)
);

CREATE TABLE payment_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Nullable to record invalid/unmatched callbacks without inventing a payment.
    payment_attempt_id BIGINT REFERENCES payment_attempts (id),
    deduplication_key VARCHAR(200) NOT NULL UNIQUE,
    signature_valid BOOLEAN NOT NULL,
    processing_status VARCHAR(20) NOT NULL DEFAULT 'RECEIVED'
        CHECK (processing_status IN ('RECEIVED', 'PROCESSED', 'REJECTED', 'FAILED')),
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ,
    error_message VARCHAR(500),
    CHECK (processed_at IS NULL OR processed_at >= received_at),
    CHECK (processing_status <> 'PROCESSED' OR
        (signature_valid AND payment_attempt_id IS NOT NULL AND processed_at IS NOT NULL))
);

CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_code VARCHAR(60) NOT NULL UNIQUE,
    booking_item_id BIGINT NOT NULL UNIQUE REFERENCES booking_items (id),
    verification_token VARCHAR(128) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'ISSUED' CHECK (status IN ('ISSUED', 'USED', 'CANCELLED')),
    issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    used_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (used_at IS NULL OR used_at >= issued_at),
    CHECK (status <> 'USED' OR used_at IS NOT NULL)
);

CREATE INDEX idx_route_stops_station ON route_stops (station_id);
CREATE INDEX idx_trips_route_status ON trips (route_id, status);
CREATE INDEX idx_trips_vehicle ON trips (vehicle_id);
CREATE INDEX idx_trip_stops_search ON trip_stops (station_id, departure_time, trip_id);
CREATE INDEX idx_bookings_user_created ON bookings (user_id, created_at DESC);
CREATE INDEX idx_bookings_trip_status ON bookings (trip_id, status);
CREATE INDEX idx_bookings_expiry ON bookings (expires_at) WHERE status = 'PENDING_PAYMENT';
CREATE INDEX idx_booking_items_seat ON booking_items (trip_seat_id);
CREATE INDEX idx_payment_attempts_booking ON payment_attempts (booking_id, created_at DESC);
CREATE INDEX idx_payment_attempts_reconciliation ON payment_attempts (reconciliation_status, created_at)
    WHERE reconciliation_status = 'REVIEW_REQUIRED';
CREATE INDEX idx_payment_events_attempt ON payment_events (payment_attempt_id);

